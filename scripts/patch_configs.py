"""Produce the pack's config/ overrides from the configs the mods generate.

Mods write their default configs on first launch of the dev instance; this
script copies only the files we change, applying documented edits. Every edit
must match exactly once, so a mod update that renames a key fails loudly
instead of silently shipping a no-op.

Ownership: this script owns exactly the files listed in EDITS. It never deletes
config/ as a whole (0.1.0 did, which also erased config/heracles, the quest book
generated by gen_quests.py). Source instance: $PH_INSTANCE (default ProjectHorizon-dev).
"""
import json, os, re, shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LONG = chr(92) * 2 + '?' + chr(92)  # Windows long-path prefix
if os.name == "nt" and not str(ROOT).startswith(LONG):
    ROOT = Path(LONG + str(ROOT))
SRC = Path(os.environ["APPDATA"]) / "PrismLauncher/instances" / os.environ.get("PH_INSTANCE", "ProjectHorizon-dev") / "minecraft/config"
OUT = ROOT / "config"
LOCK = json.loads((ROOT / "manifests/lock.json").read_text())
SHADER = next(s["file"] for s in LOCK["shaders"] if s["slug"] == "complementary-reimagined")

# file -> list of (regex, replacement, reason)
EDITS = {
    "apotheosis/apotheosis.cfg": [
        (r'B:"Restrict Charms to Curios"=false', 'B:"Restrict Charms to Curios"=true',
         "Potion charms only work from curio slots - stops 20 charms in an inventory stacking buffs."),
        (r'I:"Boss Spawn Cooldown"=3600', 'I:"Boss Spawn Cooldown"=6000',
         "Apotheosis bosses stay special next to Mowzie's/Cataclysm encounters."),
    ],
    "simplyswords/weapon_attributes.toml": [
        *[(rf"^{m}_damageModifier = 3\.0$", f"{m}_damageModifier = 1.0",
           f"{m} Simply Swords weapons: +3 -> +1 so they sidegrade vanilla/Apotheosis weapons instead of replacing them.")
          for m in ("iron", "gold", "diamond", "netherite")],
    ],
    "simplyswords/loot.toml": [
        (r"^standardLootTableWeight = 0\.1$", "standardLootTableWeight = 0.08", "fewer filler weapons in chests"),
        (r"^rareLootTableWeight = 0\.4$", "rareLootTableWeight = 0.25", "rare weapons stay rare"),
        (r"^runicLootTableWeight = 0\.7$", "runicLootTableWeight = 0.35", "runic weapons compete with Apotheosis affix loot"),
        (r"^uniqueHardPity = 75$", "uniqueHardPity = 100", "uniques are milestone finds"),
    ],
    "voxy-config.json": [
        (r'"service_threads": 4', '"service_threads": 3', "Balanced: leave CPU for worldgen + factories (6-core target)."),
    ],
    "iris.properties": [
        (r"^shaderPack=$", f"shaderPack={SHADER}", "Complementary Reimagined (Voxy-aware since r5.8.1) is the default look."),
    ],
}


# Files shipped verbatim (needed before a mod's first launch, so there is no generated default to patch).
SEEDS = {
    "visualoverhaul.json": ('{\n  "firstLaunch": false\n}\n',
                            "Visual Overhaul's first-launch hook writes its config from a PackRepository mixin before MidnightLib "
                            "registers it (NPE at Options.loadSelectedResourcePacks; client crash, tested). Its built-in packs still "
                            "load (visualoverhaul:rounddiscs seen in the pack list)."),
}


# 0.3.0 expansion: pristine first-launch defaults are snapshotted in config_defaults/ (captured from the
# ProjectHorizon-expansion candidate before any override was shipped), so these edits stay idempotent.
DEFAULTS = ROOT / "config_defaults"
EXPANSION_EDITS = {
    "effectual.json": [
        ('"caveDust": true', '"caveDust": false', "Cave Dust owns underground dust (no double dust layers)."),
        ('"snowFootprints": true', '"snowFootprints": false', "Footprint Particle owns footprints."),
        ('"lanternImprovements": true', '"lanternImprovements": false', "Swinging Lanterns owns lantern behaviour."),
        ('"blockPlaceEffect": true', '"blockPlaceEffect": false', "Particle Interactions owns block place/break particles."),
        ('"runDust": true', '"runDust": false', "Footprint Particle owns running/snow dust; no doubled footstep puffs."),
    ],
    "bettercombat/client.json5": [
        ('"isDebugOBBEnabled": true', '"isDebugOBBEnabled": false', "Crisp hits: no debug hit-box outlines drawn around targets."),
    ],
    "footprintparticle.json": [
        ('"waterSplashLevel": "PLAYER_ONLY"', '"waterSplashLevel": "DISABLED"', "Subtle Effects owns water splashes; no second splash on entering water."),
    ],
    "particlerain/config.json": [
        ('"rainVolume": 0.2', '"rainVolume": 0.0', "Cool Rain owns rain audio (Particle Rain stays visual); avoids three layered rain loops."),
        ('"snowVolume": 0.1', '"snowVolume": 0.0', "Same: one owner for precipitation audio."),
    ],
    "punchy_moves/camera.json": [
        ('"elytraCamera": true', '"elytraCamera": false', "Auto Third Person owns the elytra/vehicle camera switch; one camera owner per state."),
    ],
}


def main():
    report = []
    for rel, edits in EXPANSION_EDITS.items():
        text = (DEFAULTS / rel).read_text(encoding="utf-8")
        for old, new, why in edits:
            if text.count(old) != 1:
                raise SystemExit(f"{rel}: {old!r} matched {text.count(old)} times")
            text = text.replace(old, new)
            report.append(f"| `{rel}` | `{new}` | {why} |")
        out = OUT / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(text.encode("utf-8"))
    for rel, (text, why) in SEEDS.items():
        out = OUT / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(text.encode("utf-8"))   # LF, byte-identical across runs/OSes
        report.append(f"| `{rel}` | (seed file) | {why} |")
    for rel, edits in EDITS.items():
        if not (SRC / rel).exists():
            raise SystemExit(f"{SRC / rel} missing: launch the dev instance once (PH_INSTANCE) or use build_all --no-configs")
        text = (SRC / rel).read_text(encoding="utf-8")
        for pat, rep, why in edits:
            text, n = re.subn(pat, rep, text, flags=re.M)
            if n == 0 and len(re.findall("^" + re.escape(rep) + "$", text, flags=re.M)) + text.count(rep) >= 1:
                n = 1   # source instance already carries the shipped value (overrides were copied into it): idempotent
            if n != 1:
                raise SystemExit(f"{rel}: pattern {pat!r} matched {n} times")
            report.append(f"| `{rel}` | `{rep.strip()}` | {why} |")
        out = OUT / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
    (ROOT / "manifests/config_changes.md").write_text(
        "| File | Setting | Reason |\n|---|---|---|\n" + "\n".join(report) + "\n", encoding="utf-8")
    print(f"patched {len(EDITS)} files, {len(report)} settings")


if __name__ == "__main__":
    main()
