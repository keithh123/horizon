"""Build resourcepacks/Horizon-16x.zip, the original 16x Project Horizon pack (deterministic).

Everything here is drawn by this script (no third-party art): the Heracles quest book item texture, the pack icon,
and the sound-event table for Horizon's reward cues. Cue events map to *vanilla* sound events (no new audio files),
so a pack author can re-point any cue by editing sounds.json. The same table is written to kubejs/assets so the
cues exist even if the pack is switched off (kubejs/assets/horizon/sounds.json is written by this script too).

  python scripts/gen_resourcepack.py
"""
import json, os, struct, zlib, zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LONG = chr(92) * 2 + '?' + chr(92)
if os.name == "nt" and not str(ROOT).startswith(LONG):
    ROOT = Path(LONG + str(ROOT))
EPOCH = (1980, 2, 1, 0, 0, 0)

# cue -> list of (vanilla event, volume, pitch). One entry is picked at random per play; cues that should layer are
# played as two events by the caller (see kubejs horizon_events.js / QuestPopupScreen).
CUES = {
    "cue.item_found":    [("minecraft:block.amethyst_block.chime", 0.35, 1.5)],
    "cue.rare_loot":     [("minecraft:block.amethyst_block.resonate", 0.6, 1.1), ("minecraft:block.amethyst_cluster.break", 0.5, 1.2)],
    "cue.mythic":        [("minecraft:block.beacon.power_select", 0.7, 1.4)],
    "cue.trophy":        [("minecraft:ui.toast.challenge_complete", 0.6, 1.0)],
    "cue.legend_slain":  [("minecraft:entity.player.levelup", 0.5, 0.8)],
    "cue.quest_claim":   [("minecraft:entity.experience_orb.pickup", 0.8, 0.9), ("minecraft:entity.player.levelup", 0.45, 1.35)],
}


def sounds_json():
    out = {}
    for name, entries in CUES.items():
        out[name] = {"subtitle": "horizon.subtitle." + name.split(".")[1],
                     "sounds": [{"name": ev, "type": "event", "volume": vol, "pitch": pit} for ev, vol, pit in entries]}
    return json.dumps(out, indent=2) + "\n"


def png(rows, pal, w=None):
    h = len(rows); w = w or len(rows[0])
    raw = b"".join(b"\x00" + b"".join(bytes(pal[c]) for c in r) for r in rows)
    def ch(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    return (b"\x89PNG\r\n\x1a\n" + ch(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
            + ch(b"IDAT", zlib.compress(raw, 9)) + ch(b"IEND", b""))


BOOK = [
    "................", "..KKKKKKKKKKKK..", ".KRRRRRRRRRRRRK.", ".KRDDDDDDDDDDRK.", ".KRDWWWWWWWWDRK.", ".KRDWGGGGGGWDRK.",
    ".KRDWWWWWWWWDRK.", ".KRDWGGGGGGWDRK.", ".KRDWWWWWWWWDRK.", ".KRDWGGGWWWWDRK.", ".KRDWWWWWWWWDRK.", ".KRDDDDDDDDDDRK.",
    ".KRRRRRRRRRRRRK.", ".KKKKKKKKKKKKKK.", "..KYYYYYYYYYYK..", "................"]
PAL = {".": (0, 0, 0, 0), "K": (40, 26, 12, 255), "R": (150, 40, 40, 255), "D": (104, 26, 30, 255),
       "W": (236, 224, 196, 255), "G": (150, 120, 60, 255), "Y": (232, 200, 114, 255)}


def icon():
    # 64x64 horizon: dusk gradient above a dark ground line with a gold sun
    def pixel(x, y):
        if y >= 40:
            return (27, 23, 19, 255) if y != 40 else (107, 78, 31, 255)
        if (x - 32) ** 2 + (y - 40) ** 2 <= 100:
            return (232, 200, 114, 255)
        t = y / 40
        return (int(44 + 150 * t), int(34 + 90 * t), int(70 - 10 * t), 255)
    raw = b"".join(b"\x00" + b"".join(bytes(pixel(x, y)) for x in range(64)) for y in range(64))
    def ch(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    return (b"\x89PNG\r\n\x1a\n" + ch(b"IHDR", struct.pack(">IIBBBBB", 64, 64, 8, 6, 0, 0, 0))
            + ch(b"IDAT", zlib.compress(raw, 9)) + ch(b"IEND", b""))


def main():
    entries = {
        "pack.mcmeta": json.dumps({"pack": {"pack_format": 34, "description": "§6Project Horizon 16x§r §7quest book, reward cues"}}, indent=2).encode(),
        "pack.png": icon(),
        "assets/heracles/textures/item/quest_book.png": png(BOOK, PAL),
        "assets/horizon/sounds.json": sounds_json().encode(),
        "assets/horizon/lang/en_us.json": json.dumps({
            "horizon.subtitle.item_found": "Item discovered", "horizon.subtitle.rare_loot": "Rare loot",
            "horizon.subtitle.mythic": "Mythic discovery", "horizon.subtitle.trophy": "Trophy earned",
            "horizon.subtitle.legend_slain": "Legend slain", "horizon.subtitle.quest_claim": "Quest rewards claimed"}, indent=2).encode(),
        "CREDITS.txt": b"Project Horizon 16x. All art and the sound-event table are original, generated by scripts/gen_resourcepack.py.\n"
                       b"Cues reuse vanilla sound events only. MIT.\n",
    }
    out = ROOT / "resourcepacks" / "Horizon-16x.zip"
    out.parent.mkdir(exist_ok=True)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for name in sorted(entries):
            zi = zipfile.ZipInfo(name, EPOCH); zi.compress_type = zipfile.ZIP_DEFLATED; zi.external_attr = 0o644 << 16
            z.writestr(zi, entries[name])
    base = ROOT / "kubejs" / "assets" / "horizon" / "sounds.json"
    base.parent.mkdir(parents=True, exist_ok=True)
    base.write_bytes(entries["assets/horizon/sounds.json"])
    print(f"wrote {out.name} ({out.stat().st_size} bytes) and kubejs/assets/horizon/sounds.json")


if __name__ == "__main__":
    main()
