"""docs/EXPANSION_CHECKLIST.md: one row per requested audit entry (+ the Fresh Animations add-ons), derived from
manifests/roster.json, lock.json, ports_lock.json and manifests/validation.json (hand-recorded test evidence).

  python scripts/gen_checklist.py <audit.json>      (default audit path: manifests/expansion_audit.json)

Statuses: implemented (native build pinned) | implemented (port) | implemented (shipped verbatim) | already in Horizon
| replaced | blocked | not ported yet | excluded by user | not installed (addon). 'verified' comes only from
validation.json, never from metadata.
"""
import json, os, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LONG = chr(92) * 2 + '?' + chr(92)
if os.name == "nt" and not str(ROOT).startswith(LONG):
    ROOT = Path(LONG + str(ROOT))


def main():
    audit = json.loads(Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / "manifests/expansion_audit.json").read_text(encoding="utf-8"))
    roster = json.loads((ROOT / "manifests/roster.json").read_text())
    lock = json.loads((ROOT / "manifests/lock.json").read_text())
    ports = json.loads((ROOT / "manifests/ports_lock.json").read_text())["ports"]
    val = json.loads((ROOT / "manifests/validation.json").read_text(encoding="utf-8"))
    base = {m["slug"] for m in json.loads((ROOT / "manifests/baseline_slugs.json").read_text())}
    mods = {m["slug"]: m for m in lock["mods"]}
    packs = {p["slug"]: p for p in lock.get("resourcepacks", [])}
    port_by = {p["replaces_slug"]: p for p in ports if p.get("replaces_slug")}
    excl = {e["slug"]: e for e in roster.get("excluded", [])}
    rows = []
    entries = [(r["requested"], r["slug"], r["status"]) for r in audit["rows"]] + \
              [(a["project"], a["slug"], "FA add-on") for a in audit["animation_addons"]]
    for req, slug, astat in entries:
        req = req.replace("�", "'")
        if astat == "Excluded by user":
            rows.append((req, slug or "-", "excluded by user", "-", "Not requested (user excluded)."))
            continue
        if slug in base:
            st, ver = "already in Horizon", mods[slug]["version"]
        elif slug in mods:
            st, ver = "implemented (native build pinned)", mods[slug]["version"]
        elif slug in packs:
            st, ver = "implemented (resource pack)", packs[slug]["version"]
        elif slug in port_by:
            p = port_by[slug]
            st = "implemented (shipped verbatim)" if p["kind"] == "verbatim" else \
                 "implemented (metadata repack of existing port)" if p["kind"] == "repack" else "implemented (source port)"
            ver = p["file"]
        else:
            e = excl.get(slug) or next((x for k, x in excl.items() if slug and slug in k), None)
            st, ver = (e["status"], "-") if e else ("MISSING FROM CHECKLIST", "-")
        ev = val.get(slug, {})
        why = (excl.get(slug) or {}).get("reason", "")
        rows.append((req, slug, st, ver, "; ".join(x for x in [ev.get("evidence", ""), ev.get("unverified", ""), why] if x)))
    out = ["# Expansion checklist (0.3.0)", "",
           "Generated by `scripts/gen_checklist.py` from the audit, roster, lock, ports lock and `manifests/validation.json`.",
           "'implemented' means pinned/built and shipped; evidence states what was actually tested. Nothing here is a claim that",
           "an untested interaction works.", "",
           "| Requested | Project | Status | Version / file | Evidence and reasons |", "|---|---|---|---|---|"]
    out += [f"| {a} | `{b}` | {c} | {d} | {e.replace('|', '/')} |" for a, b, c, d, e in rows]
    counts = {}
    for r in rows:
        counts[r[2].split(" (")[0]] = counts.get(r[2].split(" (")[0], 0) + 1
    out += ["", "Totals: " + ", ".join(f"{k}: {v}" for k, v in sorted(counts.items()))]
    (ROOT / "docs/EXPANSION_CHECKLIST.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(counts)
    if "MISSING FROM CHECKLIST" in counts:
        raise SystemExit("some entries have no status")


if __name__ == "__main__":
    main()
